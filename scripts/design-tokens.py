#!/usr/bin/env python3
"""Generate committed QML/Lua/CSS/native design constants from one reviewed source."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs(root=ROOT):
    tokens = json.loads((root / 'config/design-tokens.json').read_text(encoding='utf-8'))
    qml = ['// Generated by scripts/design-tokens.py; edit config/design-tokens.json.', 'pragma Singleton', 'import QtQuick', '', 'QtObject {']
    for name, token in tokens.items():
        value = token['value']
        literal = value['expression'] if isinstance(value, dict) else json.dumps(value, ensure_ascii=False)
        qml.append(f'    readonly property {token["type"]} {name}: {literal}')
    qml.append('}')
    result = {'shell/ui/Theme.qml': '\n'.join(qml) + '\n'}
    def template(name, css=False):
        text = (root / ('config/templates/' + name + '.in')).read_text(encoding='utf-8')
        def replace(match):
            value = tokens[match[1]]['value']
            return str(value).lstrip('#') if not css else str(value)
        return re.sub(r'@([A-Za-z]+)@', replace, text)
    result['config/titlebars.lua'] = '-- Generated by scripts/design-tokens.py.\n' + template('titlebars.lua')
    result['config/window-management.lua'] = '-- Generated by scripts/design-tokens.py.\n' + template('window-management.lua')
    result['assets/gtk/hud.css'] = '/* Generated by scripts/design-tokens.py. */\n' + template('hud.css', True)
    result['native/titlebars/design.hpp'] = '''// Generated by scripts/design-tokens.py.
#pragma once
namespace ShittimHUD::Design {
inline constexpr double glyphRatio = %s;
inline constexpr double strokeRatio = %s;
inline constexpr double accentR = %s, accentG = %s, accentB = %s;
inline constexpr double surfaceR = %s, surfaceG = %s, surfaceB = %s;
}
''' % tuple([tokens[key]['value'] for key in ('windowGlyphRatio', 'windowStrokeRatio')] +
            [int(tokens[key]['value'][i:i+2], 16) / 255 for key in ('accent', 'surfaceElevated') for i in (1, 3, 5)])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, expected in outputs().items():
        target = ROOT / name
        if args.write:
            with target.open('w', encoding='utf-8', newline='\n') as stream:
                stream.write(expected)
        elif not target.is_file() or target.read_text(encoding='utf-8') != expected:
            stale.append(name)
    if stale:
        parser.exit(1, 'Design tokens out of date: ' + ', '.join(stale) + '\nRun: python3 scripts/design-tokens.py --write\n')


if __name__ == '__main__':
    main()
